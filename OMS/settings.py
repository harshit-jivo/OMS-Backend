def _csv(value, default=()):
    """Parse a comma-separated .env value into a list, tolerating an inline
    comment the same way `_parse_bool` does."""
    raw = str(value or '').split('#', 1)[0]
    items = [item.strip() for item in raw.split(',') if item.strip()]
    return items or list(default)


def _parse_bool(value, default=False):
    if value is None:
        return default
    if isinstance(value, bool):
        return value

    # Tolerate an inline "# comment" after the value — python-decouple does NOT
    # strip these, so "true   # note" would otherwise parse as neither true nor false.
    normalized = str(value).split('#', 1)[0].strip().lower()
    if normalized in {'1', 'true', 'yes', 'on'}:
        return True
    if normalized in {'0', 'false', 'no', 'off', '', 'release'}:
        return False
    return default


