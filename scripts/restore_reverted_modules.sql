-- Restore the objects the production revert migrations dropped.
--
-- WHY THIS EXISTS
-- ---------------
-- `production` removed HAIS, Combo Mapping and Scheme Engine v2 on 26 Aug 2026
-- and applied four migrations that dropped their tables and columns:
--
--     orders/0058_revert_scheme_v2   orders/0059_revert_combo
--     users/0028_revert_combo        users/0029_drop_hais
--
-- The merge of `test` into `production` restores all three modules, so those
-- four migrations were deleted from the branch. That fixes the code and the
-- migration graph, but it CANNOT fix the live database: the migrations that
-- originally CREATED these objects (orders/0052, orders/0053, orders/0054,
-- users/0026_partyproductassignment_combo_free_item, HAIS/0001_initial) are
-- still recorded as applied in django_migrations, so `migrate` will never
-- re-run them. The rows say the tables exist; the database says otherwise.
--
-- Without this script, `manage.py migrate` on live ABORTS partway through, at
-- orders/0057_scheme_uom_pcs_box_only, which alters `scheme_triggers` and
-- `scheme_benefits` -- tables that are not there.
--
-- WHEN TO RUN
-- -----------
-- Once, on the live database, BEFORE `python manage.py migrate`:
--
--     psql -v ON_ERROR_STOP=1 -d order_management -f scripts/restore_reverted_modules.sql
--
-- (No psql meta-commands are used, so it also runs through any driver.)
--
-- The DDL is taken from `manage.py sqlmigrate` for the creating migrations, so
-- what it builds is exactly what Django's model state expects. Every statement
-- is guarded, so this is idempotent, and a harmless no-op on the test database
-- (10.10.101.117) where the reverts were never applied and the objects are
-- still present and populated.
--
-- It creates EMPTY tables. Nothing is restored into them, because there is
-- nothing to restore: the reverts dropped them while they held no rows on live.

