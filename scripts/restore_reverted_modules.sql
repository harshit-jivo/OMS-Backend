             'scheme_benefits_scheme_id_88fc7cd7_fk_schemes_id',
             'FOREIGN KEY ("scheme_id") REFERENCES "schemes" ("id") DEFERRABLE INITIALLY DEFERRED'),
            ('scheme_triggers',
             'scheme_triggers_scheme_id_9d21d6fe_fk_schemes_id',
             'FOREIGN KEY ("scheme_id") REFERENCES "schemes" ("id") DEFERRABLE INITIALLY DEFERRED'),
            ('scheme_assignments',
             'scheme_assignments_scheme_id_37ff4f0c_fk_schemes_id',
             'FOREIGN KEY ("scheme_id") REFERENCES "schemes" ("id") DEFERRABLE INITIALLY DEFERRED'),
            ('scheme_assignments',
             'scheme_assignments_created_by_id_c9d9ef4f_fk_users_user_id',
             'FOREIGN KEY ("created_by_id") REFERENCES "users_user" ("id") DEFERRABLE INITIALLY DEFERRED'),
            ('scheme_assignments',
             'scheme_assignments_scheme_id_scope_type_sco_2a951207_uniq',
             'UNIQUE ("scheme_id", "scope_type", "scope_value", "category")'),
            ('order_item_schemes',
             'order_item_schemes_scheme_v2_id_23ccf535_fk_schemes_id',
             'FOREIGN KEY ("scheme_v2_id") REFERENCES "schemes" ("id") DEFERRABLE INITIALLY DEFERRED'),
            ('order_item_schemes',
             'order_item_schemes_benefit_id_44af6170_fk_scheme_benefits_id',
             'FOREIGN KEY ("benefit_id") REFERENCES "scheme_benefits" ("id") DEFERRABLE INITIALLY DEFERRED')
        ) AS t(tbl, conname, definition)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = c.conname) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', c.tbl, c.conname, c.definition);
        END IF;
    END LOOP;
END
$restore$;

